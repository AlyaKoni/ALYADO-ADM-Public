<#
.SYNOPSIS
Extracts general tenant and Azure information such as Entra ID (AAD) apps, licenses, groups, policies, roles, users, MFA configurations, and security settings, as well as Azure subscriptions, templates, Logic Apps, Automation Runbooks, and DNS Zones.

.DESCRIPTION
The 20_ExtractGeneralInformation.ps1 script automates the extraction of general cloud environment information for backup and documentation purposes. It loads the Alya environment configuration, starts a transcript log to capture the process, and sequentially executes extraction scripts for Entra ID (AAD), Automation, Azure, Network, and Security configurations. Each called script handles its own login (Az and/or MgGraph). All results are logged in a time-stamped file located in the AlyaLogs directory.

.INPUTS
None. The script does not accept input from the pipeline.

.OUTPUTS
Transcript log file containing the extraction process details and output files generated by the extraction scripts.

.EXAMPLE
PS> .\20_ExtractGeneralInformation.ps1
This command executes the script and performs the extraction of general information, saving logs and export files to the configured directories.

.NOTES
